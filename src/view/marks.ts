/** 시설의 기호 열쇠: 종류가 같은 소방 시설 가운데 항공대와 해양구조대는 이름으로 가린다 */
export function facilityMarkKey(kind: string, name: string): string {
  if (name.includes('항공')) return 'heliport';
  if (name.includes('해양')) return 'harbor';
  return FACILITY_MARK[kind] ? kind : 'public';
}

const cache = new Map<string, Path2D>();
/** 기호 하나를 (x, y) 가운데에 size 화소 크기로 그린다 */
export function drawMark(ctx: CanvasRenderingContext2D, d: string, x: number, y: number, size: number, color: string): void {
  let p = cache.get(d);
  if (!p) { p = new Path2D(d); cache.set(d, p); }
  const k = size / 24;
  ctx.save();
  ctx.translate(x - size / 2, y - size / 2);
  ctx.scale(k, k);
  ctx.fillStyle = color;
  ctx.fill(p, 'evenodd');
  ctx.restore();
}
